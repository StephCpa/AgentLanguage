"""Generate typed SDK bindings from a fixed Catalog; no tools are executed."""
from __future__ import annotations

import argparse
import ast
from pathlib import Path
import re
from typing import Any

from .errors import AL0Error, TypeCheckError
from .ir import Catalog
from .sdk import PlanBuilder


def require_catalog(builder: PlanBuilder, fingerprint: str) -> None:
    builder._bind_catalog(fingerprint)


class _Names:
    def __init__(self) -> None:
        self.used: set[str] = set()

    def take(self, prefix: str, original: str) -> str:
        slug = re.sub('[^A-Za-z0-9_]', '_', original).strip('_') or 'value'
        base = prefix+'_'+slug
        name, suffix = base, 2
        while name in self.used:
            name, suffix = base+'_'+str(suffix), suffix+1
        self.used.add(name)
        return name


def generate_bindings(catalog: Catalog) -> str:
    """Return deterministic Python source for this exact catalog snapshot.

    All user-controlled names/keys become quoted literals or allocated Python
    identifiers. The generated bindings delegate to the existing PlanBuilder.
    JSON is explicit and recursive; arbitrary runtime-selected schemas remain
    available through the general SDK, outside these static bindings.
    """
    schemas = catalog.record_schemas()
    names = _Names()
    types = {name: names.take('Schema', name) for name in sorted(schemas)}
    tags = {name: names.take('Tool', name) for name in sorted(catalog.tools)}
    python_types = {'Text': 'str', 'Int': 'int', 'Bool': 'bool', 'Json': 'JsonValue', 'InferenceError': 'InferenceError', 'InferenceRejection': 'InferenceRejection', **types}
    methods: dict[tuple[str, ...], str] = {}
    lines = [
        '"""Generated by al0.codegen. Regenerate after changing the Catalog."""',
        'from __future__ import annotations', '',
        'from typing import Any, Literal, Sequence, TypeAlias, TypedDict, overload',
        'from al0.codegen import require_catalog',
        'from al0.errors import TypeCheckError',
        'from al0.inference import InferenceError',
        'from al0.inference_admission import InferenceRejection',
        'from al0.sdk import (Candidate, Cap, Checked, DataRef, Intent, Observation, Operation,',
        '                     OpRef, PlanBuilder, Ref, Snapshot, ToolRef, Variant)', '',
        "JsonValue: TypeAlias = str | int | bool | None | list['JsonValue'] | dict[str, 'JsonValue']", '',
        'CATALOG_FINGERPRINT = '+repr(catalog.fingerprint()),
    ]
    # A normal Catalog is acyclic because schema() only permits earlier types.
    # Explicit dependency ordering also handles registration order differences.
    remaining = set(schemas)
    defined = {'Text', 'Int', 'Bool', 'Json', 'InferenceError', 'InferenceRejection'}
    while remaining:
        ready = sorted(name for name in remaining if set(schemas[name].values()) <= defined)
        if not ready:
            raise TypeCheckError('catalog schemas contain an unresolved dependency or cycle')
        for name in ready:
            fields = ', '.join(repr(field)+': '+python_types[typ] for field, typ in sorted(schemas[name].items()))
            lines += ['', f'{types[name]} = TypedDict({types[name]!r}, {{{fields}}})']
            defined.add(name)
            remaining.remove(name)
    for tag in tags.values():
        lines += ['', '', f'class {tag}:', '    """Nominal tool identity, not a runtime capability or output payload."""', '    pass']
    lines += ['', '', 'class Bindings:',
              '    def __init__(self, builder: PlanBuilder) -> None:',
              '        require_catalog(builder, CATALOG_FINGERPRINT)',
              '        self._builder = builder', '',
              '    def _verify(self) -> None:',
              '        require_catalog(self._builder, CATALOG_FINGERPRINT)']

    def method(key: str, signature: str, body: list[str]) -> str:
        prefix, original = key.split(':', 1)
        name = names.take(prefix, original)
        methods[(prefix, original)] = name
        lines.extend(['', '    def '+name+signature+':', '        self._verify()', *['        '+line for line in body]])
        return name

    for schema in sorted(python_types):
        typ = python_types[schema]
        method('literal:'+schema, f'(self, name: str, value: {typ}) -> Ref[{typ}]',
               [f'return self._builder.literal(name, {schema!r}, value)'])
        name = names.take('parameter', schema)
        methods[('parameter', schema)] = name
        for kind, result in [('Data', typ), ('Candidate', f'Candidate[{typ}]'),
                             ('Observation', f'Observation[{typ}]'), ('Checked', f'Checked[{typ}]')]:
            default = "='Data'" if kind == 'Data' else ''
            lines += ['', '    @overload', f"    def {name}(self, name: str, *, kind: Literal[{kind!r}]{default}, predicates: Sequence[str]=()) -> Ref[{result}]: ..."]
        lines += [f"    def {name}(self, name: str, *, kind: str='Data', predicates: Sequence[str]=()) -> Ref[Any]:",
                  '        self._verify()', "        if kind not in ('Data', 'Candidate', 'Observation', 'Checked'):",
                  "            raise TypeCheckError('generated schema parameters require a data/evidence kind')",
                  f'        return self._builder.parameter(name, {schema!r}, kind=kind, predicates=predicates)']
        for field, target in sorted(schemas.get(schema, {}).items()):
            name = names.take('field', schema+'_'+field)
            methods[('field', schema, field)] = name
            out = python_types[target]
            for source, result in [(f'Ref[Candidate[{typ}]]', f'Candidate[{out}]'),
                                   (f'Ref[Observation[{typ}]]', f'Observation[{out}]'),
                                   (f'Ref[{typ}] | Ref[Checked[{typ}]]', out)]:
                lines += ['', '    @overload', f'    def {name}(self, name: str, value: {source}) -> Ref[{result}]: ...']
            lines += [f'    def {name}(self, name: str, value: DataRef[{typ}]) -> Ref[Any]:',
                      '        self._verify()', f'        return self._builder.field(name, value, {field!r})']

    for tool_name, spec in sorted(catalog.tools.items()):
        inp, out, tag = python_types[spec.input_type], python_types[spec.output_type], tags[tool_name]
        binding = f'tool: ToolRef[{inp}, {tag}] = self._builder.tool({tool_name!r})'
        for operation in ('capability', 'cap_parameter'):
            method(operation+':'+tool_name, f'(self, name: str) -> Ref[Cap[{tag}]]',
                   [binding, f'return self._builder.{operation}(name, tool)'])
        if spec.kind in ('infer', 'observe', 'check'):
            result = f'Candidate[{out}]' if spec.kind == 'infer' else f'Observation[{out}]' if spec.kind == 'observe' else f'Checked[{inp}]'
            method(spec.kind+':'+tool_name, f'(self, name: str, value: DataRef[{inp}]) -> Ref[{result}]',
                   [f'tool: ToolRef[{inp}, {out}] = self._builder.tool({tool_name!r})',
                    f'return self._builder.{spec.kind}(name, tool, value)'])
            if spec.kind == 'infer':
                for operation in ('infer_result', 'infer_progress', 'try_infer'):
                    method(operation+':'+tool_name, f'(self, name: str, value: DataRef[{inp}]) -> Ref[Variant]',
                       [f'tool: ToolRef[{inp}, {out}] = self._builder.tool({tool_name!r})',
                        f'return self._builder.{operation}(name, tool, value)'])
                for operation, result in [('operation_parameter', 'Operation'), ('opref_parameter', 'OpRef')]:
                    method(operation+':'+tool_name, f'(self, name: str) -> Ref[{result}[{tag}]]',
                           [binding, f'return self._builder.{operation}(name, tool)'])
                method('resume_infer:'+tool_name, f'(self, name: str, operation: Ref[Operation[{tag}]]) -> Ref[Variant]',
                       [f"if self._builder._type_of(operation).name != {tool_name!r}:",
                        "    raise TypeCheckError('model operation belongs to another tool')",
                        'return self._builder.resume_infer(name, operation)'])
        elif spec.kind == 'action':
            method('prepare:'+tool_name, f'(self, name: str, value: Ref[{inp}] | Ref[Checked[{inp}]]) -> Ref[Intent[{tag}]]',
                   [binding, 'return self._builder.prepare(name, tool, value)'])
            for operation, result in [('intent_parameter', 'Intent'), ('operation_parameter', 'Operation'), ('opref_parameter', 'OpRef')]:
                method(operation+':'+tool_name, f'(self, name: str) -> Ref[{result}[{tag}]]',
                       [binding, f'return self._builder.{operation}(name, tool)'])
        elif spec.kind == 'reconcile':
            target = tags[spec.reconciles]
            method('reconcile:'+tool_name, f'(self, name: str, operation: Ref[Operation[{target}]]) -> Ref[Snapshot[{target}]]',
                   [binding, 'return self._builder.reconcile(name, tool, operation)'])
        else:
            raise TypeCheckError('unsupported tool kind in catalog')
    lines += ['', '', 'SCHEMA_TYPES = '+repr(types),
              ('TOOL_TAGS = ' if tags else 'TOOL_TAGS: dict[str, str] = ')+repr(tags),
              'METHOD_NAMES = '+repr(methods), '']
    source = '\n'.join(lines)
    ast.parse(source)
    return source


def main(argv: list[str] | None=None) -> int:
    # Reuse the data-only catalog format accepted by the source frontend.
    from .frontend import read_catalog, read_text
    parser = argparse.ArgumentParser(description=__doc__)
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument('--catalog', type=Path)
    source.add_argument('--demo-catalog', action='store_true')
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--check', action='store_true', help='fail on missing/stale output without writing it')
    args = parser.parse_args(argv)
    try:
        if args.catalog is not None and args.catalog.resolve() == args.output.resolve():
            raise TypeCheckError('catalog input and generated output paths must differ')
        if args.demo_catalog:
            from .demo import catalog
            specs = catalog()
        else:
            specs = read_catalog(read_text(args.catalog))
        generated = generate_bindings(specs)
        if args.check:
            if not args.output.is_file() or args.output.read_text(encoding='utf-8') != generated:
                raise TypeCheckError('generated bindings are missing or stale')
        else:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_text(generated, encoding='utf-8')
    except (AL0Error, OSError) as error:
        print(str(error))
        return 1
    print(('Checked' if args.check else 'Generated')+' bindings: '+str(args.output))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
